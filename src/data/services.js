// Build Basic / Standard / Premium packages from a base price.
const packages = (base, days, features) => [
  { name: 'Basic', price: base, delivery: days, features: features.slice(0, 2) },
  { name: 'Standard', price: Math.round(base * 2), delivery: Math.max(days - 1, 1) + 2, features: features.slice(0, 3) },
  { name: 'Premium', price: Math.round(base * 3.5), delivery: days + 5, features: features },
]

